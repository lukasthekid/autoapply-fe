#!/usr/bin/env node

/**
 * Script to generate TypeScript types from OpenAPI specification
 * Usage: npm run generate:api-types
 */

import { execSync } from 'child_process'
import { fileURLToPath } from 'url'
import { dirname, join } from 'path'
import { readFile, writeFile } from 'fs/promises'

const __filename = fileURLToPath(import.meta.url)
const __dirname = dirname(__filename)
const PROJECT_ROOT = join(__dirname, '..')

// For type generation, always use the remote API URL
// This ensures types are generated from the latest backend spec
const API_SPEC_URL = process.env.VITE_API_BASE_URL 
  ? `${process.env.VITE_API_BASE_URL}/api/openapi.json`
  : 'https://api.project100x.run.place/api/openapi.json'

const OUTPUT_FILE = join(PROJECT_ROOT, 'src/types/api-generated.ts')
const TEMP_SPEC_FILE = join(PROJECT_ROOT, 'temp-openapi.json')

async function generateTypes() {
  try {
    console.log('📡 Fetching OpenAPI specification from:', API_SPEC_URL)
    
    // Fetch the OpenAPI spec
    const response = await fetch(API_SPEC_URL)
    if (!response.ok) {
      throw new Error(`Failed to fetch OpenAPI spec: ${response.status} ${response.statusText}`)
    }
    
    const spec = await response.json()
    console.log('✅ OpenAPI spec fetched successfully')
    
    // Save spec to temp file (openapi-typescript CLI needs a file)
    await writeFile(TEMP_SPEC_FILE, JSON.stringify(spec, null, 2), 'utf-8')
    console.log('💾 Saved spec to temporary file')
    
    // Generate TypeScript types using openapi-typescript CLI
    console.log('🔨 Generating TypeScript types...')
    const types = execSync(
      `npx openapi-typescript "${TEMP_SPEC_FILE}" --output "${OUTPUT_FILE}"`,
      { encoding: 'utf-8', stdio: 'pipe' }
    )
    
    // Read the generated file and add header
    const generatedContent = await readFile(OUTPUT_FILE, 'utf-8')
    const header = `/**
 * Auto-generated TypeScript types from OpenAPI specification
 * 
 * DO NOT EDIT THIS FILE MANUALLY
 * This file is generated automatically from: ${API_SPEC_URL}
 * 
 * To regenerate, run: npm run generate:api-types
 * 
 * Generated at: ${new Date().toISOString()}
 */

`
    
    await writeFile(OUTPUT_FILE, header + generatedContent, 'utf-8')
    
    // Clean up temp file
    try {
      await import('fs/promises').then(fs => fs.unlink(TEMP_SPEC_FILE))
    } catch (e) {
      // Ignore cleanup errors
    }
    
    console.log('✅ TypeScript types generated successfully at:', OUTPUT_FILE)
    console.log('💡 You can now import types from "@/types/api-generated"')
    console.log('📝 Example: import type { paths, components } from "@/types/api-generated"')
    
  } catch (error) {
    console.error('❌ Error generating API types:', error.message)
    if (error.stdout) console.error('STDOUT:', error.stdout)
    if (error.stderr) console.error('STDERR:', error.stderr)
    process.exit(1)
  }
}

generateTypes()

